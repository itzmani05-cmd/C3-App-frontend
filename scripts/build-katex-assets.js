// Bundles KaTeX (script, stylesheet and woff2 fonts) into src/utils/katexAssets.js so formulas typeset offline.
// Run `node scripts/build-katex-assets.js` after upgrading the katex dev dependency.
const fs = require('fs');
const path = require('path');

const dist = path.join(__dirname, '..', 'node_modules', 'katex', 'dist');
const js = fs.readFileSync(path.join(dist, 'katex.min.js'), 'utf8');
let css = fs.readFileSync(path.join(dist, 'katex.min.css'), 'utf8');

// Every web view carries this whole payload, so drop the font families that exam questions practically never use
// (Fraktur, Script, Sans-serif, Typewriter, bold Caligraphic). Those glyphs fall back to the default font.
const UNUSED_FAMILIES = ['KaTeX_Fraktur', 'KaTeX_Script', 'KaTeX_SansSerif', 'KaTeX_Typewriter', 'KaTeX_Caligraphic'];
css = css.replace(/@font-face\{[^}]*\}/g, (rule) => {
  const family = /font-family:"?([\w-]+)"?/.exec(rule)?.[1];
  const dropped = UNUSED_FAMILIES.includes(family) && !(family === 'KaTeX_Caligraphic' && /font-weight:400/.test(rule));
  return dropped ? '' : rule;
});

// Keep only the woff2 source of every @font-face and inline it as a data URI.
// The terminator (";" or the rule's closing "}") must be kept: the last declaration of a minified rule ends with "}".
css = css.replace(/src:([^;}]*)([;}])/g, (match, body, end) => {
  const woff2 = /url\((fonts\/[^)]+\.woff2)\)\s*format\("woff2"\)/.exec(body);
  if (!woff2) return match;
  const data = fs.readFileSync(path.join(dist, woff2[1])).toString('base64');
  return `src:url(data:font/woff2;base64,${data}) format("woff2")${end}`;
});

const out = `// Generated by scripts/build-katex-assets.js. Do not edit.\nexport const KATEX_JS = ${JSON.stringify(js)};\nexport const KATEX_CSS = ${JSON.stringify(css)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'utils', 'katexAssets.js'), out);
console.log('katexAssets.js:', Math.round(out.length / 1024), 'KB');
